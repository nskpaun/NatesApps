// ---------- kit/parts.json: the real-world shopping list (generated by kit/tools/make_bom.py) ----------

/** A cheaper budget alternative ([KitItem.swap]) or a nicer one ([KitItem.upgrade]). */
data class KitAlt(val product: String, val mpn: String, val unitUsd: Double, val note: String)

data class KitItem(
    val id: String, val category: String, val role: String, val product: String, val mpn: String, val qty: Int, val unitUsd: Double,
    val buyUrl: String, val optional: Boolean, val excluded: Boolean, val swap: KitAlt?, val upgrade: KitAlt?,
) {
    /** Counts toward the build budget (not the optional desk mat, not filament). */
    val core: Boolean get() = !optional && !excluded
    fun unit(swaps: Boolean): Double = if (swaps && swap != null) swap.unitUsd else unitUsd
    fun line(swaps: Boolean): Double = unit(swaps) * qty
}

data class Kit(val currency: String, val pricesChecked: String, val items: List<KitItem>) {
    fun coreTotal(swaps: Boolean): Double = items.filter { it.core }.sumOf { it.line(swaps) }
    fun optionalTotal(swaps: Boolean): Double = items.filter { it.optional && !it.excluded }.sumOf { it.line(swaps) }
    fun excludedTotal(swaps: Boolean): Double = items.filter { it.excluded }.sumOf { it.line(swaps) }
    /** Categories in file order. */
    val categories: List<Pair<String, List<KitItem>>> get() = items.groupBy { it.category }.toList()
}

object KitParser {
    /** Never throws: anything unreadable gives an empty kit. Items without a product are skipped. */
    fun parse(text: String?): Kit {
        val o = runCatching { JSONObject(text ?: "") }.getOrNull() ?: return Kit("USD", "", emptyList())
        val arr = o.optJSONArray("items")
        val items = (0 until (arr?.length() ?: 0)).mapNotNull { i ->
            val it = arr?.optJSONObject(i) ?: return@mapNotNull null
            val product = it.s("product").ifBlank { return@mapNotNull null }
            KitItem(
                id = it.s("id").ifBlank { "item$i" }, category = it.s("category").ifBlank { "Other" }, role = it.s("role"),
                product = product, mpn = it.s("mpn"), qty = it.optInt("qty", 1).coerceAtLeast(1), unitUsd = it.money("unit_usd"),
                buyUrl = it.s("buy_url"), optional = it.optBoolean("optional", false), excluded = it.optBoolean("excluded", false),
                swap = alt(it.optJSONObject("swap")), upgrade = alt(it.optJSONObject("upgrade")),
            )
        }
        return Kit(o.s("currency").ifBlank { "USD" }, o.s("prices_checked"), items)
    }

    private fun alt(o: JSONObject?): KitAlt? {
        if (o == null) return null
        val p = o.s("product").ifBlank { return null }
        if (!o.has("unit_usd")) return null
        return KitAlt(p, o.s("mpn"), o.money("unit_usd"), o.s("note"))
    }

    private fun JSONObject.s(k: String): String = if (has(k) && !isNull(k)) optString(k, "").trim() else ""
    private fun JSONObject.money(k: String): Double = optDouble(k, 0.0).let { if (it.isNaN() || it.isInfinite() || it < 0) 0.0 else it }
}

object KitRepo {
    @Volatile private var kit: Kit? = null
    fun kit(ctx: Context): Kit = kit ?: synchronized(this) {
        kit ?: KitParser.parse(runCatching { ctx.assets.open("kit/parts.json").bufferedReader().use { it.readText() } }.getOrNull()).also { kit = it }
    }
    fun reset() { kit = null }
}

fun fmtUsd(v: Double): String = String.format(Locale.US, "$%,.2f", v)
/** "+$12.00" / "−$120.99" (true minus sign). */
fun fmtDelta(v: Double): String = (if (v < 0) "−" else "+") + fmtUsd(abs(v))

/** Opens [url] in the browser. False when there is no URL or nothing can open it. */
fun openUrl(ctx: Context, url: String): Boolean {
    if (url.isBlank()) return false
    return try {
        val i = Intent(Intent.ACTION_VIEW, Uri.parse(url)).addFlags(if (ctx is android.app.Activity) 0 else Intent.FLAG_ACTIVITY_NEW_TASK)
        ctx.startActivity(i); true
    } catch (e: ActivityNotFoundException) { false } catch (e: SecurityException) { false }
}

// ---------- the Buy view (Specs > Buy) ----------

@Composable
fun BuyList(app: AppState, pad: Dp, maxW: Dp) {
    val ctx = LocalContext.current
    val kit = remember { KitRepo.kit(ctx) }
    var swaps by rememberSaveable { mutableStateOf(false) }
    LazyColumn(Modifier.fillMaxSize().testTag("buy"), contentPadding = PaddingValues(top = 22.dp, bottom = 40.dp)) {
        if (kit.items.isEmpty()) {
            item(key = "empty") {
                Panel(Modifier.readable(maxW).padding(horizontal = pad).testTag("buy-empty")) {
                    Kicker("Shopping list")
                    Spacer(Modifier.height(10.dp))
                    Text("The parts list isn't bundled in this build.", color = C.ink, fontSize = 15.sp, lineHeight = 22.sp)
                    Spacer(Modifier.height(6.dp))
                    Caption("It comes from kit/parts.json, generated by kit/tools/make_bom.py.", color = C.muted)
                }
            }
            return@LazyColumn
        }
        item(key = "totals") { BuyTotals(kit, swaps, { swaps = it }, Modifier.readable(maxW).padding(horizontal = pad)) }
        kit.categories.forEach { (cat, list) ->
            item(key = "c-$cat") {
                Row(Modifier.readable(maxW).padding(horizontal = pad).padding(top = 26.dp, bottom = 4.dp).testTag("buy-cat-$cat"), verticalAlignment = Alignment.CenterVertically) {
                    Box(Modifier.width(2.dp).height(13.dp).background(C.amber))
                    Spacer(Modifier.width(10.dp))
                    Tracked(cat, Modifier.weight(1f), size = 10.5.sp, color = C.ink, weight = FontWeight.Normal, tracking = .16f)
                    Text(fmtUsd(list.sumOf { it.line(swaps) }), color = C.ink.copy(alpha = .8f), fontSize = 12.5.sp, maxLines = 1)
                }
            }
            items(list, key = { "i-${it.id}" }) { item ->
                BuyRow(item, swaps, Modifier.readable(maxW).padding(horizontal = pad)) {
                    if (item.buyUrl.isNotBlank() && !openUrl(ctx, item.buyUrl)) app.toast = "No browser to open the link"
                }
            }
        }
        item(key = "foot") {
            Text(
                "Tap a part to open where to buy it. Totals leave out shipping, tax, the optional desk mat and the filament for the printed parts. " +
                    "Upgrades are never counted.",
                color = C.muted, fontSize = 12.sp, lineHeight = 18.sp, modifier = Modifier.readable(maxW).padding(horizontal = pad).padding(top = 22.dp),
            )
        }
    }
}

@Composable
private fun BuyTotals(kit: Kit, swaps: Boolean, onSwaps: (Boolean) -> Unit, modifier: Modifier) {
    val core = kit.coreTotal(swaps)
    val saving = kit.coreTotal(false) - kit.coreTotal(true)
    Column(modifier) {
        Panel(Modifier.fillMaxWidth(), padding = 18.dp) {
            Row(verticalAlignment = Alignment.Bottom) {
                Column(Modifier.weight(1f)) {
                    Kicker("Shopping list")
                    Spacer(Modifier.height(6.dp))
                    Text("${kit.items.count { it.core }} items to buy", color = C.ink, fontSize = 16.sp, fontWeight = FontWeight.Light)
                }
                Column(horizontalAlignment = Alignment.End) {
                    Text(fmtUsd(core), Modifier.testTag("buy-total"), color = C.amber, fontSize = 24.sp, fontWeight = FontWeight.Light, maxLines = 1)
                    MicroLabel(if (swaps) "With budget swaps" else "Core build", color = C.muted, tracking = .24f, weight = FontWeight.Light, maxLines = 1)
                }
            }
            Spacer(Modifier.height(12.dp))
            Hairline(color = C.line.copy(alpha = .7f))
            ToggleRow(
                "Budget swaps", swaps, onSwaps, Modifier.padding(top = 4.dp).testTag("buy-swaps"),
                sub = if (saving > 0.005) "Cheaper picks where there is one; saves ${fmtUsd(saving)}" else "Cheaper picks where there is one",
            )
            Hairline(color = C.line.copy(alpha = .7f))
            Spacer(Modifier.height(10.dp))
            MicroLabel("Not in the budget", color = C.muted, tracking = .22f, weight = FontWeight.Light)
            Spacer(Modifier.height(4.dp))
            val optional = kit.optionalTotal(swaps)
            val excluded = kit.excludedTotal(swaps)
            if (optional > 0) AsideRow("Optional (desk mat)", optional)
            if (excluded > 0) AsideRow("Filament", excluded)
        }
        Spacer(Modifier.height(12.dp))
        Caption(
            if (kit.pricesChecked.isNotBlank()) "Prices checked ${kit.pricesChecked}; they move often." else "Prices move often.",
            Modifier.testTag("buy-checked"), color = C.muted,
        )
    }
}

@Composable
private fun AsideRow(label: String, usd: Double) {
    Row(Modifier.fillMaxWidth().padding(vertical = 4.dp), verticalAlignment = Alignment.CenterVertically) {
        Text(label, Modifier.weight(1f), color = C.ink.copy(alpha = .75f), fontSize = 13.sp)
        Text(fmtUsd(usd), color = C.ink.copy(alpha = .75f), fontSize = 13.sp, maxLines = 1)
    }
}

@Composable
private fun BuyRow(item: KitItem, swaps: Boolean, modifier: Modifier, onOpen: () -> Unit) {
    val link = item.buyUrl.isNotBlank()
    val swapped = swaps && item.swap != null
    Column(modifier) {
        Column(
            Modifier.fillMaxWidth().testTag("buy-${item.id}")
                .then(if (link) Modifier.clickable(role = Role.Button, onClickLabel = "Open where to buy", onClick = onOpen) else Modifier)
                .padding(start = 12.dp, top = 12.dp, bottom = 12.dp),
        ) {
            Row(verticalAlignment = Alignment.Top) {
                Column(Modifier.weight(1f).padding(end = 10.dp)) {
                    Row(verticalAlignment = Alignment.Top) {
                        Text(
                            item.product.nbUnits(), Modifier.weight(1f, fill = false), color = if (swapped) C.ink.copy(alpha = .55f) else C.ink.copy(alpha = .92f),
                            fontSize = 13.5.sp, lineHeight = 18.sp,
                        )
                        if (link) Icon(Icons.AutoMirrored.Outlined.OpenInNew, null, tint = C.muted, modifier = Modifier.padding(start = 6.dp, top = 2.dp).size(13.dp))
                    }
                    if (item.mpn.isNotBlank()) Text(item.mpn, color = C.titanium.copy(alpha = .8f), fontSize = 11.sp, fontFamily = FontFamily.Monospace, modifier = Modifier.padding(top = 3.dp))
                }
                Column(horizontalAlignment = Alignment.End) {
                    Text(
                        fmtUsd(item.line(false)), color = if (swapped) C.muted else C.ink, fontSize = 13.sp, maxLines = 1,
                        textDecoration = if (swapped) TextDecoration.LineThrough else null,
                    )
                    Text("${item.qty} × ${fmtUsd(item.unitUsd)}".nbUnits(), color = C.muted, fontSize = 11.sp, maxLines = 1, modifier = Modifier.padding(top = 2.dp))
                }
            }
            if (item.role.isNotBlank()) Text(item.role.nbUnits(), color = C.muted, fontSize = 12.sp, lineHeight = 17.sp, modifier = Modifier.padding(top = 6.dp))
            if (item.swap != null && swaps) AltRow("Swap", item.swap, item, active = true)
            if (item.upgrade != null) AltRow("Upgrade", item.upgrade, item, active = false)
        }
        Hairline(color = C.line.copy(alpha = .45f))
    }
}

/** Secondary row under an item: a swap (counted when Budget swaps is on) or an upgrade (never counted). */
@Composable
private fun AltRow(kind: String, alt: KitAlt, item: KitItem, active: Boolean) {
    val delta = (alt.unitUsd - item.unitUsd) * item.qty
    val accent: Color = if (active) C.amber else C.muted
    Row(Modifier.fillMaxWidth().height(IntrinsicSize.Min).padding(top = 10.dp).testTag("buy-${kind.lowercase(Locale.ROOT)}-${item.id}"), verticalAlignment = Alignment.Top) {
        Box(Modifier.padding(vertical = 3.dp).width(1.dp).fillMaxHeight().background(accent.copy(alpha = .6f)))
        Spacer(Modifier.width(10.dp))
        Column(Modifier.weight(1f).padding(end = 10.dp)) {
            MicroLabel(kind, color = accent, tracking = .2f, maxLines = 1)
            Text(alt.product.nbUnits(), color = C.ink.copy(alpha = if (active) .9f else .7f), fontSize = 12.5.sp, lineHeight = 17.sp, modifier = Modifier.padding(top = 2.dp))
            if (alt.mpn.isNotBlank()) Text(alt.mpn, color = C.titanium.copy(alpha = .7f), fontSize = 10.5.sp, fontFamily = FontFamily.Monospace, modifier = Modifier.padding(top = 2.dp))
        }
        Column(horizontalAlignment = Alignment.End) {
            Text(fmtUsd(alt.unitUsd * item.qty), color = if (active) C.ink else C.ink.copy(alpha = .7f), fontSize = 12.5.sp, maxLines = 1)
            Text(fmtDelta(delta), color = if (active) C.amber else C.muted, fontSize = 11.sp, maxLines = 1, textAlign = TextAlign.End, modifier = Modifier.padding(top = 2.dp))
        }
    }
}
